function run_project
%RUN_PROJECT Run the validated suspension analysis workflow.

projectRoot = fileparts(mfilename('fullpath'));
addpath(fullfile(projectRoot, 'config'));
addpath(fullfile(projectRoot, 'src'));
addpath(fullfile(projectRoot, 'tests'));

cfg = project_configuration();
dataDir = fullfile(projectRoot, 'outputs', 'simulation_data');
if ~isfolder(dataDir)
    mkdir(dataDir);
end

roadNames = {'smooth', 'speed_bump', 'pothole', 'rough'};
speedsKmh = [30, 60];
results = cell(numel(roadNames), numel(speedsKmh));
summaryRows = cell(numel(roadNames) * numel(speedsKmh), 1);
row = 0;

fprintf('Phase 1: running %d quarter-car cases...\n', numel(results));
for iRoad = 1:numel(roadNames)
    for iSpeed = 1:numel(speedsKmh)
        roadName = roadNames{iRoad};
        speedKmh = speedsKmh(iSpeed);
        fprintf('  %-10s at %2d km/h\n', roadName, speedKmh);
        result = simulate_case(roadName, speedKmh, cfg, cfg.solver);
        results{iRoad, iSpeed} = result;

        fileName = sprintf('%s_%02dkmh.csv', roadName, speedKmh);
        writetable(result.data, fullfile(dataDir, fileName));
        row = row + 1;
        summaryRows{row} = analyze_loads(result);
    end
end

summaryTable = vertcat(summaryRows{:});
writetable(summaryTable, fullfile(projectRoot, 'outputs', 'summary.csv'));

fprintf('Running Phase 1 validation (including stricter nonzero reruns)...\n');
validation = validate_model(cfg, results, roadNames, speedsKmh);
writetable(validation.checks, fullfile(projectRoot, 'outputs', 'validation_results.csv'));
writetable(validation.convergence, fullfile(projectRoot, 'outputs', 'convergence_results.csv'));
write_validation_report(fullfile(projectRoot, 'outputs', 'validation_report.txt'), ...
    validation, cfg);

disp(summaryTable);
disp(validation.checks);
if ~validation.requiredChecksPassed
    error('Phase1:ValidationFailed', ...
        'One or more required numerical/physics validation checks failed.');
end
if validation.contactLossCount > 0
    warning('Phase1:ContactLoss', ...
        ['Predicted tire contact loss occurred in %d case(s). Negative estimated ' ...
         'normal forces were retained in the CSV files.'], validation.contactLossCount);
end
fprintf('Phase 1 checks complete. Running Phase 2 analysis and figures...\n');
phase2 = run_phase2_analysis(projectRoot, cfg, results, roadNames, speedsKmh);
disp(phase2.eventMetrics);
disp(phase2.samplingCheck);
fprintf('Phase 2 complete. Results are in %s\n', fullfile(projectRoot, 'outputs'));

fprintf('Phase 2 complete. Running Phase 3 rainflow analysis...\n');
phase3 = run_phase3_analysis(projectRoot, cfg, results, roadNames, speedsKmh);
disp(phase3.severitySummary);
disp(phase3.samplingSensitivity);
if ~phase3.validationPassed
    error('Phase3:ValidationFailed', ...
        'One or more required Phase 3 validation checks failed.');
end
fprintf('Phase 3 complete. Results are in %s\n', ...
    fullfile(projectRoot, 'outputs', 'phase3'));
if cfg.phase4.enabled
    fprintf('Phase 4: creating speed-bump animation from existing histories...\n');
    phase4 = create_animation(projectRoot, cfg, results, roadNames, speedsKmh);
    disp(phase4.summary);
    if ~phase4.rendered
        warning('Phase4:ExportUnavailable', ...
            'Animation export did not complete; see the Phase 4 status files.');
    end
    fprintf('Phase 4 complete. Results are in %s\n', ...
        fullfile(projectRoot, 'outputs', 'animation'));
end
end

function write_validation_report(filePath, validation, cfg)
fid = fopen(filePath, 'w');
if fid < 0
    error('Phase1:FileOpen', 'Could not open validation report: %s', filePath);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, 'Phase 1 validation report\n');
fprintf(fid, 'Generated by an actual MATLAB run.\n\n');
fprintf(fid, 'Baseline solver: RelTol %.3g, AbsTol %.3g.\n', ...
    cfg.solver.RelTol, cfg.solver.AbsTol);
fprintf(fid, ['Baseline MaxStep = min(output interval, pothole length/(40*speed), ' ...
    '1/(20*rough maximum temporal frequency)).\n']);
fprintf(fid, 'Strict solver: RelTol %.3g, AbsTol %.3g, half baseline MaxStep.\n', ...
    cfg.validation.strictRelTol, cfg.validation.strictAbsTol);
fprintf(fid, ['Convergence acceptance: max pointwise difference divided by the strict-run ' ...
    'peak magnitude <= %.3g for suspension force, body acceleration, and suspension deflection.\n\n'], ...
    cfg.validation.convergenceRelativeTolerance);
fprintf(fid, 'Required checks passed: %s\n', string(validation.requiredChecksPassed));
fprintf(fid, 'Cases predicting tire contact loss: %d\n', validation.contactLossCount);
if validation.contactLossCount > 0
    fprintf(fid, ['WARNING: The bilateral linear tire model predicts nonpositive total normal ' ...
        'force. Values are not clamped; post-lift-off motion is outside model validity.\n']);
else
    fprintf(fid, 'No case predicted nonpositive estimated total tire normal force.\n');
end
clear cleanup
end
